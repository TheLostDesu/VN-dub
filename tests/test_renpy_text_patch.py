MENU_SCRIPT = """define s = Character("Sakuya")
label start:
    menu:
        s "Which way?"
        "Stay":
            s "Fine."
        "Leave":
            s "Bye."
"""
MENU_TR = {"Which way?": "Какой путь?", "Fine.": "Хорошо.", "Bye.": "Пока."}


def test_parse_flags_a_menu_say_and_its_id_is_over_the_nointeract_code(make_ctx, tmp_path: Path) -> None:
    from vndub.engines import renpy as rp

    ctx, res = _project(make_ctx, tmp_path, MENU_SCRIPT, MENU_TR)
    by = {l.text_src: l for l in res.lines if l.text_src}
    assert "menu_say" in by["Which way?"].flags and "menu_say" not in by["Fine."].flags and "menu_say" not in by["Bye."].flags
    digest = rp.block_digest([rp.say_code("s", "Which way?", [], [], False)])
    assert by["Which way?"].dialogue_id == "start_" + digest  # type: ignore[attr-defined]
    assert by["Which way?"].dialogue_id != "start_" + rp.block_digest([rp.say_code("s", "Which way?", [], [], True)])  # type: ignore[attr-defined]


def test_menu_say_block_has_nointeract_with_the_flag_and_by_digest_without_it(make_ctx, tmp_path: Path) -> None:
    ctx, res = _project(make_ctx, tmp_path, MENU_SCRIPT, MENU_TR)
    ident = _ids(res)["Which way?"]
    run_stage("pack", ctx)
    text = _rpy(ctx)
    assert f'translate russian {ident}:\n\n    # s "Which way?"\n    s "Какой путь?" nointeract\n' in text
    assert 's "Хорошо."\n' in text and 's "Хорошо." nointeract' not in text

    # a project parsed by an older app: no flag on the record, the identifier's digest tells
    from vndub.manifest.io import LineRecord, read_jsonl

    old = [l.model_copy(update={"flags": [f for f in l.flags if f != "menu_say"]}) for l in read_jsonl(ctx.paths.lines, LineRecord)]
    assert not any("menu_say" in l.flags for l in old)
    write_jsonl(ctx.paths.lines, old)
    run_stage("pack", ctx)
    text = _rpy(ctx)
    assert 's "Какой путь?" nointeract\n' in text and 's "Хорошо."\n' in text and 's "Пока."\n' in text

    # an explicit nointeract in the script is not doubled
    ctx2, _ = _project(make_ctx, tmp_path / "b", SCRIPT, TR)
    run_stage("pack", ctx2)
    assert _rpy(ctx2).count('s "Выбирай." nointeract\n') == 1


