"""Ren'Py: the translated text on screen (``game/tl/<language>/vndub_dialogue.rpy`` + ``game/vndub_language.rpy``).

The team's report: the Russian voice played but the text stayed English, because the pipeline never wrote a text translation
into the patch. ``pack`` now writes one ``translate <language> <dialogue id>:`` block per translated say line (the shape
``renpy translate`` writes), a ``translate <language> strings:`` block for menu choices and captions, and a script that starts
the game in that language. There is no Ren'Py SDK here: the shapes follow renpy/translation/generation.py.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

import pytest
from engine_helpers import detect_and_parse

from vndub.manifest.io import FinalIndexRecord, write_jsonl
from vndub.stages import pack as pack_stage
from vndub.stages.common import run_stage

SCRIPT = """define s = Character("Sakuya", voice_tag="sakuya")
label start:
    voice "voice/s_0001.ogg"
    s "Welcome back, darling."
    voice sustain
    s "Still the same voice."
    s "Hello, [player]!"
    s "Lost [player] here."
    s "Quote \\"x\\" and 100%% sure {i}yes{/i}"
    s "Again."
    s "Again."
    s "Choose." nointeract
    menu:
        "Which way?"
        "Stay":
            s "Fine."
        "Leave":
            s "Bye."
"""

TR = {
    "Welcome back, darling.": "С возвращением, дорогая.",
    "Hello, [player]!": "Привет, [player]!",
    "Lost [player] here.": "Потерян здесь.",
    'Quote "x" and 100% sure yes': 'Цитата "x" и 100% точно [да] {нет}',
    "Choose.": "Выбирай.",
    "Fine.": "Хорошо.",
    "Bye.": "Пока.",
    "Which way?": "Какой путь?",
    "Still the same voice.": "Всё тот же голос.",
}


def _project(make_ctx, tmp_path: Path, script: str = SCRIPT, tr: dict[str, Any] | None = None, choices: Any = ("Остаться", "Уйти"), **sets: Any):
    g = tmp_path / "g"
    (g / "game" / "voice").mkdir(parents=True)
    (g / "game" / "script.rpy").write_text(script, encoding="utf-8")
    for n in ("s_0001", "e_0001", "e_0002"):
        (g / "game" / "voice" / f"{n}.ogg").write_bytes(b"OggS")
    ctx = make_ctx(g, sets=sets or None)
    _, _, _, res = detect_and_parse(ctx)
    write_jsonl(ctx.paths.lines, res.lines)
    rows = []
    again = 0
    for l in res.lines:
        if l.text_src == "Again.":
            again += 1
        text = (TR if tr is None else tr).get(l.text_src, "") if l.text_src != "Again." else f"Снова {again}."
        row: dict[str, Any] = {"line_id": l.line_id, "text_tgt": text, "text_tts": "ТТС " + text}
        if "menu" in l.flags and choices is not None:
            row["choices_tgt"] = list(choices)
        rows.append(row)
    ctx.paths.translation("ru").parent.mkdir(parents=True, exist_ok=True)
    ctx.paths.translation("ru").write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")
    write_jsonl(ctx.paths.final_index, [])
    return ctx, res


def _out(ctx) -> Path:
    return ctx.paths.out_engine("renpy") / "game"


def _rpy(ctx, lang: str = "russian") -> str:
    return (_out(ctx) / "tl" / lang / "vndub_dialogue.rpy").read_text(encoding="utf-8")


def _manifest(ctx) -> dict[str, Any]:
    return json.loads((ctx.paths.out_engine("renpy") / "manifest_patch.json").read_text(encoding="utf-8"))


def _ids(res) -> dict[str, str]:
    return {l.text_src: getattr(l, "dialogue_id") for l in res.lines if getattr(l, "dialogue_id", None)}


def test_block_shape_and_voice_statements(make_ctx, tmp_path: Path) -> None:
    ctx, res = _project(make_ctx, tmp_path)
    s = run_stage("pack", ctx)
    text = _rpy(ctx)
    ids = _ids(res)
    assert text.startswith("# Generated by vndub")
    welcome = ids["Welcome back, darling."]
    # the shape `renpy translate` writes: a location comment, the block header, the original as a comment, the say statement
    assert f'translate russian {welcome}:\n\n    # s "Welcome back, darling."\n    voice "voice/s_0001.ogg"\n    s "С возвращением, дорогая."\n' in text
    assert re.search(r"^# game/script\.rpy:4\ntranslate russian " + welcome, text, re.M)
    assert 'translate russian ' + ids["Choose."] + ':\n\n    # s "Choose." nointeract\n    s "Выбирай." nointeract\n' in text  # the clauses after the text stay
    assert 'voice sustain\n    s "Всё тот же голос."' in text  # a block replaces its whole group: the voice statement has to be in it
    assert s["text"] is True and s["text_lines"] == _manifest(ctx)["text"]["lines"]


def test_identifiers_are_never_repeated_and_texts_are_the_translation_not_the_tts_text(make_ctx, tmp_path: Path) -> None:
    ctx, _ = _project(make_ctx, tmp_path)
    run_stage("pack", ctx)
    text = _rpy(ctx)
    heads = re.findall(r"^translate russian (\w+):", text, re.M)
    assert len(heads) == len(set(heads)) and "Снова 1." in text and "Снова 2." in text
    assert "ТТС" not in text


def test_escaping_interpolation_and_skipped_lines(make_ctx, tmp_path: Path) -> None:
    ctx, res = _project(make_ctx, tmp_path)
    run_stage("pack", ctx)
    text = _rpy(ctx)
    assert 's "Привет, [player]!"' in text  # the original's interpolation is carried over as it is
    # `[да]` / `{нет}` are not in the original: escaped; `%` is doubled; the quotes are backslashed
    assert 's "Цитата \\"x\\" и 100%% точно [[да] {{нет}"' in text
    ids = _ids(res)
    assert ids["Lost [player] here."] not in text  # the translation dropped `[player]`: the line keeps the English text
    sk = _manifest(ctx)["text"]["skipped"]
    assert {"line_id": next(l.line_id for l in res.lines if l.text_src == "Lost [player] here."), "id": ids["Lost [player] here."], "reason": "interpolation lost"} in sk


def test_translated_string_unit() -> None:
    f = pack_stage.translated_string
    assert f("Hi [name]", "Привет [name]") == "Привет [name]"
    assert f("Hi [name]", "Привет") is None
    assert f("Hi", "Привет [x] {b} 50%") == "Привет [[x] {{b} 50%%"
    assert f("Wait{w} here", "Ждём здесь") == "Ждём здесь"  # the translator never sees {w}: it is not required any more
    assert f("Wait{w} here", "Ждём{w} здесь") == "Ждём{w} здесь"
    assert f("Wait.{nw}", "Ждём.") == "Ждём.{nw}" and f("Wait.{fast}", "Ждём.") == "Ждём.{fast}"  # a last-token tag goes back at the end
    assert f("Wait.{nw}", "Ждём.{nw}") == "Ждём.{nw}"
    assert f(" and more.", "и ещё.") == " и ещё."  # extend: the leading space stays
    assert f("See {image=x} now", "Смотри") is None and f("See {a=u}link{/a}", "Смотри") is None  # {image} and {a} stay required
    assert f("It is {i}fine{/i}", "Всё хорошо") == "Всё хорошо"  # formatting tags are dropped, the line still reads
    assert f("%(n)s apples", "яблок: %(n)s") == "яблок: %(n)s"


def test_strings_block_for_choices_and_captions(make_ctx, tmp_path: Path) -> None:
    ctx, _ = _project(make_ctx, tmp_path)
    run_stage("pack", ctx)
    text = _rpy(ctx)
    block = text[text.index("translate russian strings:") :]
    assert re.search(r'old "Stay"\n    new "Остаться"\n', block) and re.search(r'old "Leave"\n    new "Уйти"\n', block)
    assert 'old "Which way?"\n    new "Какой путь?"\n' in block  # a bare string in a menu is a caption: a string, not a block
    assert block.count("translate russian strings:") == 1
    m = _manifest(ctx)["text"]
    assert m["strings"] == 3 and m["language"] == "russian"


