import { useCallback, useEffect, useRef, useState } from "react";
import { api } from "../api/endpoints";
import { toErrorInfo } from "../api/client";
import type { Character, Design, ErrorInfo, ListenItem, Tuning, TuningListenItem } from "../api/types";
import { DEFAULT_TUNING } from "../api/types";
import { useI18n } from "../i18n";
import { useJobTracker } from "../state/progress";
import { fmtMinutes, fmtNumber } from "../util/format";
import { ErrorPanel } from "./ErrorPanel";
import { JobProgress } from "./JobProgress";
import { VoiceTuningPanel, withDefaults } from "./VoiceTuning";
import { ABPlayer, WavePlayer } from "./WavePlayer";
import { Button, Callout, Chip, Histogram, LicenseBadge, SelectField, Stars, TextField, useToast } from "./ui";

/** speaker of voiced lines shown without a name that no voice-file prefix attributes (vndub.engines.base.VOICE_OVER) */
const VOICE_OVER = "voice_over";

export function routeFor(d: Design, c: Character): string {
  if (d.kind === "clone") return "A";
  return c.voiced_lines > 0 && c.clips.length > 0 ? "B" : "P";
}

function hasOriginal(c: Character): boolean {
  return c.mode !== "unvoiced" && c.clips.length > 0;
}

export function RvcChip({ c }: { c: Character }) {
  const t = useI18n().t;
  const r = c.rvc;
  if (!r || r.state === "none") return null;
  const pct = Math.round((r.progress ?? 0) * 100);
  const tone = r.state === "done" ? "good" : r.state === "failed" ? "bad" : "info";
  return (
    <Chip tone={tone} testid={`rvc-chip-${c.speaker_id}`} title={t("casting.rvc.title")}>
      {r.state === "training" ? t("casting.rvc.training", { pct }) : t(`casting.rvc.${r.state}`)}
    </Chip>
  );
}

interface Props {
  c: Character;
  expanded: boolean;
  onToggle: () => void;
  onChanged: (c: Character) => void;
  /** characters of the project, for "apply to all similar" feedback */
  allNames: Record<string, string>;
  /** bumped from outside (voice library, automatic casting) to reload the proposals */
  refreshKey: number;
  /** automatic casting is running: do not start a generation of our own */
  suspendAutoGen?: boolean;
}

export function CharacterCard({ c, expanded, onToggle, onChanged, allNames, refreshKey, suspendAutoGen }: Props) {
  const { t } = useI18n();
  const toast = useToast();
  const sid = c.speaker_id;
  const name = c.name_tgt || c.name_src || sid;
  const original = hasOriginal(c);

  const [designs, setDesigns] = useState<Design[] | null>(null);
  const [designsError, setDesignsError] = useState<ErrorInfo | null>(null);
  const [actionError, setActionError] = useState<ErrorInfo | null>(null);
  const [choosing, setChoosing] = useState<string | null>(null);
  const [description, setDescription] = useState(c.description ?? "");
  const [age, setAge] = useState(c.age_hint ?? "");
  const [onlyNewSince, setOnlyNewSince] = useState<string | null>(null);
  const [saveVoiceOpen, setSaveVoiceOpen] = useState(false);
  const [voiceName, setVoiceName] = useState(name);
  const [listenItems, setListenItems] = useState<ListenItem[] | null>(null);
  const loadedFor = useRef<string>("");
  const fileRef = useRef<HTMLInputElement>(null);
  const [uploading, setUploading] = useState(false);

  const loadDesigns = useCallback(async () => {
    try {
      const d = await api.proposals(sid);
      setDesigns(d);
      setDesignsError(null);
    } catch (e) {
      setDesignsError(toErrorInfo(e));
    }
  }, [sid]);

  useEffect(() => {
    const key = `${sid}:${refreshKey}`;
    if (expanded && loadedFor.current !== key) {
      loadedFor.current = key;
      void loadDesigns();
    }
  }, [expanded, sid, refreshKey, loadDesigns]);

  const gen = useJobTracker({ onDone: () => void loadDesigns() });
  const autoGenerated = useRef(false);
  // a character without original audio has nothing to match a voice to: ask for a description or a sample first
  const needsBrief = !original && !description.trim() && !(designs ?? []).some((d) => d.kind === "reference");
  // first time the card is opened and nothing was proposed yet: propose three voices right away
  useEffect(() => {
    if (!expanded || suspendAutoGen || designs === null || autoGenerated.current || gen.busy || gen.job) return;
    if (needsBrief) return;
    if (designs.some((d) => d.kind !== "clone")) return;
    autoGenerated.current = true;
    void gen.start(() => api.generateDesigns(sid, 3, !original && description.trim() ? description.trim() : undefined));
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [expanded, designs, suspendAutoGen, needsBrief]);
  const listen = useJobTracker({
    onDone: (j) => {
      const items = (j.result?.items as ListenItem[] | undefined) ?? [];
      setListenItems(items);
    },
  });

  const saveChar = async (patch: Partial<Pick<Character, "gender" | "age_hint" | "description" | "name_tgt">>) => {
    try {
      onChanged(await api.putCharacter(sid, patch));
      setActionError(null);
    } catch (e) {
      setActionError(toErrorInfo(e));
    }
  };

  const choose = async (d: Design) => {
    setChoosing(d.design_id);
    setActionError(null);
    try {
      onChanged(await api.choose(sid, d.design_id, routeFor(d, c)));
    } catch (e) {
      setActionError(toErrorInfo(e));
    } finally {
      setChoosing(null);
    }
  };

  const generate = (replace: boolean) => {
    if (needsBrief) return;
    if (replace) setOnlyNewSince(new Date().toISOString());
    void gen.start(() => api.generateDesigns(sid, 3, !original && description.trim() ? description.trim() : undefined));
  };

  const upload = async (file: File | undefined) => {
    if (!file) return;
    setUploading(true);
    setActionError(null);
    try {
      await api.uploadSample(sid, file);
      await loadDesigns();
    } catch (e) {
      setActionError(toErrorInfo(e));
    } finally {
      setUploading(false);
      if (fileRef.current) fileRef.current.value = "";
    }
  };

  const saveVoice = async () => {
    try {
      await api.saveVoice(sid, voiceName.trim() || name);
      setSaveVoiceOpen(false);
      toast.show(t("casting.library.saved"));
    } catch (e) {
      setActionError(toErrorInfo(e));
    }
  };

  const clone = designs?.find((d) => d.kind === "clone") ?? null;
  const rest = (designs ?? []).filter((d) => d.kind !== "clone");
  const visible = onlyNewSince ? rest.filter((d) => (d.created ?? "") >= onlyNewSince || d.design_id === c.chosen?.design_id) : rest;
  const chosenId = c.chosen?.design_id ?? null;

  return (
    <article className={`char-card ${c.chosen ? "is-chosen" : ""}`} data-testid={`char-${sid}`} data-chosen={!!c.chosen} data-mode={c.mode}>
      <header className="char-head">
        <button type="button" className="char-toggle" aria-expanded={expanded} onClick={onToggle} data-testid={`char-toggle-${sid}`}>
          <span className="chevron" aria-hidden="true" />
          <span className="char-name">{name}</span>
          <span className="char-meta">{t("casting.lines_minutes", { lines: c.lines, minutes: fmtMinutes(c.minutes) })}</span>
        </button>
        <span className="char-chips">
          {sid === VOICE_OVER ? (
            <Chip title={t("casting.voice_over.hint")} testid="char-voice-over">
              {t("casting.voice_over.chip")}
            </Chip>
          ) : null}
          {c.mode === "unvoiced" ? <Chip tone="warn">{t("game.characters.mode.unvoiced")}</Chip> : c.mode === "mixed" ? <Chip tone="warn">{t("game.characters.mode.mixed")}</Chip> : null}
          {c.chosen ? <Chip tone="good" testid={`char-chosen-${sid}`}>{t("casting.chosen")}</Chip> : <Chip tone="neutral">{t("casting.not_chosen")}</Chip>}
          <RvcChip c={c} />
        </span>
      </header>

      {expanded ? (
        <div className="char-body">
          <div className="char-grid">
            {/* ---- left: who this is and how the original sounds ---- */}
            <section className="char-left" aria-label={t("casting.original")}>
              <div className="char-fields">
                <SelectField
                  label={t("casting.gender")}
                  value={c.gender}
                  options={[
                    { value: "m", label: t("gender.m") },
                    { value: "f", label: t("gender.f") },
                    { value: "unknown", label: t("gender.unknown") },
                  ]}
                  onChange={(v) => void saveChar({ gender: v })}
                  testid={`char-gender-${sid}`}
                />
                <TextField label={t("casting.age")} value={age} onChange={setAge} onBlur={() => age !== (c.age_hint ?? "") && void saveChar({ age_hint: age })} placeholder={t("casting.age_placeholder")} testid={`char-age-${sid}`} />
              </div>

              {original ? (
                <>
                  <h4>{t("casting.emotions")}</h4>
                  <Histogram data={c.emotion_hist ?? {}} testid={`char-hist-${sid}`} />
                  <h4>{t("casting.clips")}</h4>
                  <ul className="clips" data-testid={`char-clips-${sid}`}>
                    {c.clips.slice(0, 3).map((clip) => (
                      <li key={`${clip.kind}-${clip.line_id}`}>
                        <WavePlayer url={clip.url} kind="original" label={t(`casting.clip.${clip.kind}`)} showLabel compact testid={`clip-${sid}-${clip.kind}`} />
                        <p className="sample-text" lang="ja">
                          {clip.text_src}
                        </p>
                      </li>
                    ))}
                  </ul>
                </>
              ) : (
                <div className="no-audio" data-testid={`char-noaudio-${sid}`}>
                  <Callout tone="info">
                    <p>{t("casting.no_audio")}</p>
                  </Callout>
                  <TextField
                    label={t("casting.description")}
                    value={description}
                    onChange={setDescription}
                    onBlur={() => description !== (c.description ?? "") && void saveChar({ description })}
                    placeholder={t("casting.description_placeholder")}
                    multiline
                    rows={2}
                    testid={`char-description-${sid}`}
                  />
                </div>
              )}
            </section>

            {/* ---- right: proposed performers ---- */}
            <section className="char-right" aria-label={t("casting.proposals")}>
              <div className="proposal-head">
                <h4>{t("casting.proposals")}</h4>
                <div className="row-actions">
                  <Button small onClick={() => generate(false)} busy={gen.busy} disabled={needsBrief} data-testid={`casting-more-${sid}`} aria-label={t("casting.more_aria")}>
                    {t("casting.more")}
                  </Button>
                  <Button small onClick={() => generate(true)} disabled={gen.busy || needsBrief} data-testid={`casting-regen-${sid}`}>
                    {t("casting.regenerate")}
                  </Button>
                  <Button small onClick={() => fileRef.current?.click()} busy={uploading} data-testid={`casting-upload-${sid}`}>
                    {t("casting.upload")}
                  </Button>
                  <input ref={fileRef} type="file" accept=".wav,.mp3,audio/wav,audio/x-wav,audio/mpeg" className="sr-only" tabIndex={-1} aria-label={t("casting.upload")} onChange={(e) => void upload(e.target.files?.[0])} data-testid={`casting-upload-input-${sid}`} />
                </div>
              </div>
              <p className="hint">{t("casting.upload_hint")}</p>
              {needsBrief ? (
                <Callout tone="info" testid={`casting-brief-${sid}`}>
                  <p>{t("casting.brief_needed")}</p>
                </Callout>
              ) : null}

              {gen.job && gen.job.state !== "done" ? <JobProgress job={gen.job} onRetry={() => generate(false)} testid={`casting-gen-job-${sid}`} /> : null}
              {gen.error && !gen.job ? <ErrorPanel error={gen.error} onRetry={() => generate(false)} /> : null}
              {designsError ? <ErrorPanel error={designsError} onRetry={() => void loadDesigns()} /> : null}
              {actionError ? <ErrorPanel error={actionError} onDismiss={() => setActionError(null)} /> : null}

              {designs === null && !designsError ? <p className="hint">{t("app.loading")}</p> : null}
              {designs !== null && visible.length === 0 && !gen.busy && !needsBrief ?<p className="hint" data-testid={`casting-empty-${sid}`}>{t("casting.no_proposals")}</p> : null}

              <ul className="designs" data-testid={`designs-${sid}`}>
                {visible.map((d) => (
                  <DesignCard key={d.design_id} d={d} sid={sid} showStars={original} chosen={chosenId === d.design_id} busy={choosing === d.design_id} onChoose={() => void choose(d)} />
                ))}
              </ul>
              {onlyNewSince ? (
                <Button small variant="ghost" onClick={() => setOnlyNewSince(null)} data-testid={`casting-show-all-${sid}`}>
                  {t("casting.show_all")}
                </Button>
              ) : null}

              {original ? (
                <div className="clone-box" data-testid={`clone-box-${sid}`}>
                  <Button onClick={() => void choose(clone ?? { design_id: "clone", kind: "clone" } as Design)} busy={choosing === (clone?.design_id ?? "clone")} data-testid={`casting-clone-${sid}`}>
                    {t("casting.clone")}
                  </Button>
                  {chosenId && c.chosen?.route === "A" ? <Chip tone="good">{t("casting.chosen")}</Chip> : null}
                  <p className="hint warn-text">{t("casting.clone_warning")}</p>
                  {clone && clone.samples.length > 0 ? (
                    <ul className="design-samples">
                      {clone.samples.slice(0, 2).map((s) => (
                        <li key={s.line_id}>
                          <p className="sample-text">{s.text_tgt ?? s.text}</p>
                          <WavePlayer url={s.url} kind="performer" label={t("casting.clone")} compact />
                        </li>
                      ))}
                    </ul>
                  ) : null}
                </div>
              ) : null}

              <div className="row-actions listen-row">
                <Button variant="primary" onClick={() => void listen.start(() => api.listen(sid, 3))} busy={listen.busy} disabled={!c.chosen} data-testid={`casting-listen-${sid}`}>
                  {t("casting.listen")}
                </Button>
                {!c.chosen ? <span className="hint">{t("casting.listen_need_choice")}</span> : null}
                {c.chosen ? (
                  <Button variant="ghost" onClick={() => { setVoiceName(name); setSaveVoiceOpen(true); }} data-testid={`casting-save-voice-${sid}`}>
                    {t("casting.library.save")}
                  </Button>
                ) : null}
              </div>
              {listen.job && listen.busy ? <JobProgress job={listen.job} compact testid={`casting-listen-job-${sid}`} /> : null}
              {listen.error ? <ErrorPanel error={listen.error} /> : null}
              {listenItems && listenItems.length > 0 ? (
                <ul className="listen-results" data-testid={`listen-results-${sid}`}>
                  {listenItems.map((it) => (
                    <li key={it.line_id}>
                      <p className="sample-text">{it.text_tgt}</p>
                      <ABPlayer originalUrl={it.original_url} dubUrl={it.result_url} kind="listen" testid={`listen-${sid}-${it.line_id}`} />
                    </li>
                  ))}
                </ul>
              ) : null}
              {saveVoiceOpen ? (
                <div className="inline-dialog" role="group" aria-label={t("casting.library.save")}>
                  <TextField label={t("casting.library.name")} value={voiceName} onChange={setVoiceName} testid={`casting-voice-name-${sid}`} onEnter={() => void saveVoice()} />
                  <Button variant="primary" onClick={() => void saveVoice()} data-testid={`casting-voice-save-${sid}`}>
                    {t("common.save")}
                  </Button>
                  <Button variant="ghost" onClick={() => setSaveVoiceOpen(false)}>
                    {t("common.cancel")}
                  </Button>
                </div>
              ) : null}
            </section>
          </div>

          {c.chosen ? <CharacterTuning c={c} onChanged={onChanged} allNames={allNames} /> : null}
        </div>
      ) : null}
    </article>
  );
}

function DesignCard({ d, sid, showStars, chosen, busy, onChoose }: { d: Design; sid: string; showStars: boolean; chosen: boolean; busy: boolean; onChoose: () => void }) {
  const { t, tOr } = useI18n();
  return (
    <li className={`design ${chosen ? "is-chosen" : ""}`} data-testid={`design-${sid}-${d.design_id}`} data-chosen={chosen}>
      <div className="design-head">
        <div className="design-title">
          <strong>{t(`casting.kind.${d.kind}`)}</strong>
          <span className="muted"> {tOr(`models.${d.backend}.name`, d.backend)}</span>
        </div>
        {showStars && d.stars !== null && d.stars !== undefined ? (
          <span className="design-stars">
            <span className="stars-label">{t("casting.similarity")}</span>
            <Stars value={d.stars} title={d.spk_sim !== null && d.spk_sim !== undefined ? t("casting.stars_title", { sim: fmtNumber(d.spk_sim, 2) }) : undefined} testid={`design-stars-${sid}-${d.design_id}`} />
          </span>
        ) : null}
      </div>
      {d.description ? <p className="hint design-desc">{d.description}</p> : null}
      <ul className="design-samples">
        {d.samples.slice(0, 2).map((s, i) => (
          <li key={s.line_id || i}>
            <p className="sample-text">{s.text_tgt ?? s.text}</p>
            <WavePlayer url={s.url} kind="performer" label={t("casting.sample_n", { n: i + 1 })} compact testid={`sample-${sid}-${d.design_id}-${i}`} />
          </li>
        ))}
      </ul>
      <div className="design-foot">
        <LicenseBadge license={d.license} commercialOk={d.commercial_ok} />
        {chosen ? (
          <Chip tone="good">{t("casting.chosen")}</Chip>
        ) : (
          <Button variant="primary" small busy={busy} onClick={onChoose} data-testid={`design-choose-${sid}-${d.design_id}`}>
            {t("casting.choose")}
          </Button>
        )}
      </div>
    </li>
  );
}

function CharacterTuning({ c, onChanged, allNames }: { c: Character; onChanged: (c: Character) => void; allNames: Record<string, string> }) {
  const { t } = useI18n();
  const toast = useToast();
  const sid = c.speaker_id;
  const [value, setValue] = useState<Tuning>(withDefaults(c.tuning));
  const [items, setItems] = useState<TuningListenItem[] | null>(null);
  const [error, setError] = useState<ErrorInfo | null>(null);
  const timer = useRef<number | null>(null);
  const latest = useRef(value);
  latest.current = value;
  // the debounced save runs long after the render that created it: it must spread the character as it is now (a voice,
  // gender or RVC change made in between), not the one the card had when the first slider moved
  const current = useRef({ c, onChanged });
  current.current = { c, onChanged };

  const persist = useCallback(
    async (v: Tuning) => {
      try {
        const saved = await api.putTuning(sid, v);
        current.current.onChanged({ ...current.current.c, tuning: withDefaults(saved ?? v) });
        setError(null);
      } catch (e) {
        setError(toErrorInfo(e));
      }
    },
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [sid],
  );

  const change = (v: Tuning) => {
    setValue(v);
    if (timer.current !== null) window.clearTimeout(timer.current);
    timer.current = window.setTimeout(() => void persist(v), 700);
  };
  useEffect(
    () => () => {
      if (timer.current !== null) {
        window.clearTimeout(timer.current);
        void api.putTuning(sid, latest.current).catch(() => undefined);
      }
    },
    [sid],
  );

  const listen = useJobTracker({
    onDone: (j) => setItems((j.result?.items as TuningListenItem[] | undefined) ?? []),
  });

  const reset = () => {
    setItems(null);
    change({ ...DEFAULT_TUNING });
  };

  const applySimilar = async () => {
    try {
      if (timer.current !== null) {
        window.clearTimeout(timer.current);
        timer.current = null;
      }
      await api.putTuning(sid, latest.current);
      const res = await api.tuningApplySimilar(sid);
      const names = (res.updated ?? []).map((id) => allNames[id] ?? id).join(", ");
      toast.show(res.updated && res.updated.length > 0 ? t("tuning.applied_similar", { names }) : t("tuning.applied_none"));
    } catch (e) {
      setError(toErrorInfo(e));
    }
  };

  return (
    <div className="char-tuning">
      <VoiceTuningPanel
        value={value}
        onChange={change}
        onReset={reset}
        onListen={() => void listen.start(async () => {
          if (timer.current !== null) {
            window.clearTimeout(timer.current);
            timer.current = null;
            await api.putTuning(sid, latest.current);
          }
          return api.tuningListen(sid, latest.current);
        })}
        listenBusy={listen.busy}
        listenItems={items}
        onApplySimilar={() => void applySimilar()}
        prefix={`char-${sid}`}
      />
      {listen.job && listen.busy ? <JobProgress job={listen.job} compact /> : null}
      {listen.error ? <ErrorPanel error={listen.error} /> : null}
      {error ? <ErrorPanel error={error} onDismiss={() => setError(null)} /> : null}
    </div>
  );
}
