import { useCallback, useEffect, useMemo, useRef, useState } from "react";
import { api } from "../api/endpoints";
import { toErrorInfo } from "../api/client";
import type { Character, ErrorInfo } from "../api/types";
import { CharacterCard } from "../components/CharacterCard";
import { ErrorPanel } from "../components/ErrorPanel";
import { StepFooter } from "../components/StepFooter";
import { VoiceLibrary } from "../components/VoiceLibrary";
import { JobProgress } from "../components/JobProgress";
import { Button, Callout, Card, Dialog, PageTitle, Spinner, Tabs } from "../components/ui";
import { useI18n } from "../i18n";
import { useActiveJob, useJobTracker, useProgressState } from "../state/progress";
import { useWizard } from "../state/wizard";

type Tab = "characters" | "library";
const AUTO_KINDS = ["casting_auto"];

export default function CastingScreen() {
  const { t } = useI18n();
  const wiz = useWizard();
  const progress = useProgressState();
  const [chars, setChars] = useState<Character[] | null>(null);
  const [error, setError] = useState<ErrorInfo | null>(null);
  const [tab, setTab] = useState<Tab>("characters");
  const [open, setOpen] = useState<Record<string, boolean>>({});
  const [refreshKeys, setRefreshKeys] = useState<Record<string, number>>({});
  const [allKey, setAllKey] = useState(0);
  const [confirmOpen, setConfirmOpen] = useState(false);
  const initialised = useRef(false);
  const continueAfterAuto = useRef(false);

  const load = useCallback(async () => {
    try {
      const list = await api.characters();
      // the first card is open on the very first load
      if (!initialised.current && list[0]) {
        initialised.current = true;
        setOpen({ [list[0].speaker_id]: true });
      }
      setChars(list);
      setError(null);
    } catch (e) {
      setError(toErrorInfo(e));
    }
  }, []);

  useEffect(() => {
    void load();
  }, [load]);

  // RVC training progress and finished casting jobs change the characters: refresh while that is going on.
  const training = (chars ?? []).some((c) => c.rvc && (c.rvc.state === "queued" || c.rvc.state === "training"));
  useEffect(() => {
    if (!training) return;
    const iv = window.setInterval(() => void load(), 4000);
    return () => window.clearInterval(iv);
  }, [training, load]);

  const finishedRvc = Object.values(progress.jobs).filter((j) => j.kind === "rvc_train" && j.state !== "running" && j.state !== "queued").length;
  useEffect(() => {
    if (finishedRvc > 0) void load();
  }, [finishedRvc, load]);

  const update = useCallback((c: Character) => {
    setChars((cur) => (cur ? cur.map((x) => (x.speaker_id === c.speaker_id ? c : x)) : cur));
  }, []);

  const names = useMemo(() => Object.fromEntries((chars ?? []).map((c) => [c.speaker_id, c.name_tgt || c.name_src || c.speaker_id])), [chars]);
  const chosenCount = (chars ?? []).filter((c) => c.chosen).length;
  const total = chars?.length ?? 0;
  const missing = total - chosenCount;

  // "Автоматический кастинг" is a GPU job: it proposes designs for characters that have none, picks the
  // top-ranked voice for everybody and queues RVC training. Afterwards every card reloads its proposals.
  const autoJob = useJobTracker({
    onDone: () => {
      void load();
      setAllKey((k) => k + 1);
      if (continueAfterAuto.current) {
        continueAfterAuto.current = false;
        void wiz.next("casting");
      }
    },
    onFinal: (j) => {
      if (j.state !== "done") continueAfterAuto.current = false;
    },
  });
  const activeAuto = useActiveJob(AUTO_KINDS);
  useEffect(() => {
    if (activeAuto && !autoJob.job) autoJob.attach(activeAuto);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [activeAuto?.id]);
  const autoBusy = autoJob.busy;
  const autoCast = () => void autoJob.start(() => api.autoCast());
  const autoResult = autoJob.job?.state === "done" ? autoJob.job.result : null;
  const autoChosen = autoResult?.chosen && typeof autoResult.chosen === "object" ? Object.keys(autoResult.chosen as object).length : null;
  const autoGenerated = Array.isArray(autoResult?.generated) ? (autoResult?.generated as unknown[]).length : null;

  const next = async () => {
    if (missing > 0) setConfirmOpen(true);
    else await wiz.next("casting");
  };

  return (
    <>
      <PageTitle title={t("casting.title")} intro={t("casting.intro")} testid="casting-title" />

      <Card testid="casting-toolbar">
        <div className="row-actions">
          <Button variant="primary" busy={autoBusy} onClick={autoCast} disabled={total === 0} data-testid="casting-auto">
            {t("casting.auto")}
          </Button>
          <span className="hint" data-testid="casting-progress" role="status">
            {t("casting.chosen_count", { n: chosenCount, total })}
          </span>
        </div>
        <p className="hint">{t("casting.auto_hint")}</p>
        {autoJob.job ? (
          <JobProgress job={autoJob.job} onRetry={autoCast} showLog={autoJob.job.state !== "done"} compact={autoJob.job.state === "done"} testid="casting-auto-job" />
        ) : null}
        {autoJob.error && !autoJob.job ? <ErrorPanel error={autoJob.error} onRetry={autoCast} /> : null}
        {autoResult && autoChosen !== null ? (
          <p className="hint" data-testid="casting-auto-result" role="status">
            {t("casting.auto_done", { chosen: autoChosen, generated: autoGenerated ?? 0 })}
          </p>
        ) : null}
      </Card>

      <Tabs
        label={t("casting.title")}
        value={tab}
        onChange={setTab}
        tabs={[
          { value: "characters", label: t("casting.tab.characters"), testid: "casting-tab-characters" },
          { value: "library", label: t("casting.tab.library"), testid: "casting-tab-library" },
        ]}
      />

      {error ? <ErrorPanel error={error} onRetry={() => void load()} /> : null}
      {chars === null && !error ? <Spinner label={t("app.loading")} /> : null}

      {tab === "characters" && chars ? (
        chars.length === 0 ? (
          <Callout tone="info" testid="casting-no-characters">
            {t("casting.no_characters")}
          </Callout>
        ) : (
          <div className="char-list" data-testid="casting-characters">
            {chars.map((c) => (
              <CharacterCard
                key={c.speaker_id}
                c={c}
                expanded={!!open[c.speaker_id]}
                onToggle={() => setOpen((cur) => ({ ...cur, [c.speaker_id]: !cur[c.speaker_id] }))}
                onChanged={update}
                allNames={names}
                refreshKey={(refreshKeys[c.speaker_id] ?? 0) + allKey}
                suspendAutoGen={autoBusy}
              />
            ))}
          </div>
        )
      ) : null}

      {tab === "library" && chars ? (
        <VoiceLibrary
          characters={chars}
          onImported={(sid) => {
            setRefreshKeys((k) => ({ ...k, [sid]: (k[sid] ?? 0) + 1 }));
            setOpen((cur) => ({ ...cur, [sid]: true }));
          }}
        />
      ) : null}

      <Dialog
        open={confirmOpen}
        onClose={() => setConfirmOpen(false)}
        title={t("casting.confirm.title")}
        testid="casting-confirm"
        actions={
          <>
            <Button onClick={() => setConfirmOpen(false)} data-testid="casting-confirm-back">
              {t("casting.confirm.back")}
            </Button>
            <Button
              variant="primary"
              data-autofocus
              onClick={() => {
                setConfirmOpen(false);
                continueAfterAuto.current = true;
                autoCast();
              }}
              data-testid="casting-confirm-auto"
            >
              {t("casting.confirm.auto")}
            </Button>
          </>
        }
      >
        <p>{t("casting.confirm.text", { n: missing })}</p>
      </Dialog>

      <StepFooter step="casting" canNext={total > 0 && !autoBusy} onNext={next} />
    </>
  );
}
